function gains = manual_gains(mode, coriolis)
%MANUAL_GAINS Hand-tuned gains for one controller mode and factorization.
%
% Start with the shared baseline in generalDefault(), then set any
% scenario-specific overrides in defaultEntry(). This keeps common tuning in
% one location without forcing all six experiments to share final values.

gains = defaultEntry(scenarioKey(mode, coriolis));
end

function gains = defaultEntry(key)
%DEFAULTENTRY Scenario registry for manual gains.
%
% Each case starts from the general baseline. Add only the fields that must
% differ for that experiment; untouched fields retain the shared value.

gains = generalDefault();

switch key
    case 'nominal_c1'
        gains = struct('KRdiag', [0.01 0.01 2.0], ...
         'Kxidiag', [0.4 0.4 0.4], ...
         'LambdaDiag', [0.1 0.1 0.1 0.1638 0.2499 0.1605], ...
         'kd', 1.5, 'ks', 1.0, 'alpha', 0.5, ...
         'gammaE', [0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001], ...
         'gammaB', 0.001);

    case 'nominal_c2'
        gains = struct('KRdiag', [100 100 200], ...
         'Kxidiag', [5 5 5], ...
         'LambdaDiag', [100 100 100 10 10 10], ...
         'kd', 1.5, 'ks', 1.0, 'alpha', 0.5, ...
         'gammaE', [0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001], ...
         'gammaB', 0.001);

    case 'euclidean_c1'
        gains = struct('KRdiag', [0.01 0.01 2.0], ...
         'Kxidiag', [0.4 0.4 0.4], ...
         'LambdaDiag', [0.1 0.1 0.1 0.1638 0.2499 0.1605], ...
         'kd', 1.5, 'ks', 1.0, 'alpha', 0.5, ...
         'gammaE', [0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001], ...
         'gammaB', 0.001);

    case 'euclidean_c2'
        % Scenario-specific manual overrides for Euclidean adaptation/C2.

    case 'bregman_c1'
        gains = struct('KRdiag', [0.01 0.01 2.0], ...
         'Kxidiag', [0.4 0.4 0.4], ...
         'LambdaDiag', [0.1 0.1 0.1 0.1638 0.2499 0.1605], ...
         'kd', 1.5, 'ks', 1.0, 'alpha', 0.5, ...
         'gammaE', [0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001], ...
         'gammaB', 0.001);

    case 'bregman_c2'
        % Scenario-specific manual overrides for Bregman adaptation/C2.

    otherwise
        error('agc:config:manual_gains:UnknownScenario', 'Unknown scenario key: %s.', key);
end
end

function gains = generalDefault()
%GENERALDEFAULT Shared manual-gain baseline for every experiment.

gains = struct('KRdiag', [0.01 0.01 2.0], ...
         'Kxidiag', [0.4 0.4 0.4], ...
         'LambdaDiag', [0.1 0.1 0.1 0.1638 0.2499 0.1605], ...
         'kd', 1.5, 'ks', 1.0, 'alpha', 0.5, ...
         'gammaE', [0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001;0.001], ...
         'gammaB', 0.001);
end

function key = scenarioKey(mode, coriolis)
key = sprintf('%s_%s', lower(char(string(mode))), lower(char(string(coriolis))));
end
